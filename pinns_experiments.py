# 1. SIMULATION ENGINE
# ==========================================
dt = 0.01
sim_time = 5.0
steps = int(sim_time / dt)
t = np.linspace(0, sim_time, steps)

def run_experiment(robot_instance, pinn_model, motor_degradation=1.0):

    q_actual = torch.tensor([0.0, 0.4], dtype=torch.float32)
    dq_actual = torch.tensor([0.75, 0.0], dtype=torch.float32)
    q_hist = []

    Kp = torch.diag(torch.tensor([120.0, 120.0], dtype=torch.float32))
    Kd = torch.diag(torch.tensor([20.0, 20.0], dtype=torch.float32))

    for step in range(steps):
        t_curr = t[step]
        q_ref = torch.tensor([0.5 * np.sin(1.5 * t_curr), 0.4 * np.cos(1.5 * t_curr)], dtype=torch.float32)
        dq_ref = torch.tensor([0.75 * np.cos(1.5 * t_curr), -0.6 * np.sin(1.5 * t_curr)], dtype=torch.float32)
        ddq_ref = torch.tensor([-1.125 * np.sin(1.5 * t_curr), -0.9 * np.cos(1.5 * t_curr)], dtype=torch.float32)

        # Calculate PINN controller effort
        u = tracking_controller(pinn_model, q_actual, dq_actual, q_ref, dq_ref, ddq_ref, Kp, Kd)

        # Inject motor fault
        u[1] = u[1] * motor_degradation

        # Forward dynamics step
        ddq = robot_instance.forward_dynamics(q_actual, dq_actual, u)
        dq_actual = dq_actual + dt * ddq
        q_actual = q_actual + dt * dq_actual

        q_hist.append(q_actual.numpy().copy())

    return np.array(q_hist)

# Reference Trajectory array
q_ref_hist = np.array([[0.5 * np.sin(1.5 * t_c), 0.4 * np.cos(1.5 * t_c)] for t_c in t])

# Run Scenarios
q_baseline = run_experiment(GroundTruthRobot(), pinn_loaded)

robot_heavy = GroundTruthRobot()
robot_heavy.m2 = 3.0
q_heavy = run_experiment(robot_heavy, pinn_loaded)

robot_broken = GroundTruthRobot()
q_broken = run_experiment(robot_broken, pinn_loaded, motor_degradation=0.3)

robot_moon = GroundTruthRobot()
robot_moon.g = 1.62
q_moon = run_experiment(robot_moon, pinn_loaded)

