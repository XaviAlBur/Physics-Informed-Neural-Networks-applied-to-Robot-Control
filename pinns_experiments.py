def calculate_rmse(q_actual, q_reference):
    return np.sqrt(np.mean((q_actual - q_reference) ** 2))

rmse_val = [
    calculate_rmse(q_baseline, q_ref_hist),
    calculate_rmse(q_heavy, q_ref_hist),
    calculate_rmse(q_broken, q_ref_hist),
    calculate_rmse(q_moon, q_ref_hist)
]

